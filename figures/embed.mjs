// Packs the built Anatomy figures into src/39k-anatomy-figures.js so the single-file app can show them.
// Run after rebuilding a figure:  node figures/relay-bench/build.mjs && node figures/embed.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const HERE = dirname(fileURLToPath(import.meta.url));
const figs = {
  relay: readFileSync(join(HERE, "relay-bench", "relay-bench.html"), "utf8"),
  linescan: readFileSync(join(HERE, "line-scan", "line-scan.html"), "utf8"),
};
writeFileSync(join(HERE, "..", "src", "39k-anatomy-figures.js"),
  "/* Generated by figures/embed.mjs — do not edit by hand. Figures built with the Anatomy skill (MIT, see THIRD_PARTY_NOTICES.md). */\n" +
  "const ANATOMY_HTML = " + JSON.stringify(figs).replace(/<\//g, "<\\/") + ";\n");
console.log("embedded", Object.keys(figs).join(", "));
