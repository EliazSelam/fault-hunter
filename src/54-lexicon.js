const HEB = /[֐-׿]/;
function lexFound(text, alias) {
  let exact = false; if (alias[0] === '=') { exact = true; alias = alias.slice(1); }
  const a = alias.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&');
  if (!HEB.test(alias)) return new RegExp('(?<![A-Za-z0-9])' + a + '(?![A-Za-z0-9])').test(text);
  if (/[^\u0590-\u05FF]$/.test(alias)) return text.includes(alias);
  // Hebrew: up to two prefix letters (ו ה ב כ ל מ ש) unless exact, optional plural/construct suffix, no gluing inside another word
  return new RegExp('(?:^|[^\\u0590-\\u05FF])' + (exact ? '' : '(?:[והבכלמש]{0,2})') + a + '(?:ים|ות|י|ת)?(?=$|[^\\u0590-\\u05FF])').test(text);
}
function lexDefined(defs, entry) { return [entry[0], ...entry[2]].some(a => lexFound(defs, a)); }
/* rows to add to a lesson's words table: every lexicon term used in the body (or in an added definition) and not yet defined */
function lexRows(ownWords, body) {
  const rows = [], have = ownWords.map(w => w[0]);
  let text = body;
  for (let pass = 0; pass < 6; pass++) {
    const defs = have.join(' | ');
    const add = LEX.filter(e => e[2].some(a => lexFound(text, a)) && !lexDefined(defs, e));
    if (!add.length) break;
    add.forEach(e => { rows.push([e[0], e[1]]); have.push(e[0]); text += ' \n ' + e[1]; });
  }
  return rows;
}

