function hebGlossify(root) {
  if (!root) return;
  const used = new Set([...root.querySelectorAll('.gl')].map(a => a.dataset.g));
  const skip = GL_SKIP + ',.zlesson,.zcomp,table th';
  HEB_GL.forEach(([key, re]) => {
    if (used.has(key)) return;
    const w = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (w.nextNode()) {
      const n = w.currentNode; if (!n.nodeValue.trim() || n.parentElement.closest(skip)) continue;
      const m = re.exec(n.nodeValue); if (!m) continue;
      const start = m.index + m[1].length, word = m[2];
      const after = n.splitText(start); const rest = after.splitText(word.length);
      const a = document.createElement('abbr'); a.className = 'gl'; a.tabIndex = 0; a.dataset.g = key; a.textContent = word; a.setAttribute('role', 'button');
      const d = document.createElement('span'); d.className = 'gdef'; d.textContent = ' (' + GSHORT[key] + ')';
      after.replaceWith(a); a.after(d); used.add(key); void rest; break;
    }
  });
}
